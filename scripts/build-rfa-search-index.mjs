import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const SITES = [
  { key: 'main', dir: 'main', baseUrl: 'https://royalfamilyacademy.org/' },
  { key: 'nurseryandprimaryschool', dir: 'nurseryandprimaryschool', baseUrl: 'https://nurseryandprimaryschool.royalfamilyacademy.org/' },
  { key: 'highschool', dir: 'highschool', baseUrl: 'https://highschool.royalfamilyacademy.org/' },
  { key: 'sixthform', dir: 'sixthform', baseUrl: 'https://sixthform.royalfamilyacademy.org/' }
];

const PLACEHOLDER_RE = /INSERT VERIFIED|INSERT RFA-APPROVED|Verify before publication|Content note:|Pending RFA approval|placeholder/i;
const SKIP_TEXT_RE = /^(read more|learn more|explore|view more|back to top|menu|close|open menu|skip to content)$/i;

function walk(dir) {
  if (!fs.existsSync(dir)) return [];
  const out = [];
  for (const item of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, item.name);
    if (item.isDirectory()) out.push(...walk(full));
    else if (item.isFile() && item.name.toLowerCase().endsWith('.html')) out.push(full);
  }
  return out.sort();
}

function decodeEntities(value) {
  const named = {
    amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ',
    ndash: '–', mdash: '—', lsquo: '‘', rsquo: '’', ldquo: '“', rdquo: '”',
    hellip: '…', middot: '·', times: '×', copy: '©'
  };
  return String(value)
    .replace(/&#x([0-9a-f]+);/gi, (_, hex) => String.fromCodePoint(parseInt(hex, 16)))
    .replace(/&#(\d+);/g, (_, num) => String.fromCodePoint(parseInt(num, 10)))
    .replace(/&([a-z]+);/gi, (m, name) => named[name.toLowerCase()] ?? m);
}

function textOnly(value) {
  return decodeEntities(String(value || ''))
    .replace(/<br\s*\/?>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function removeNonContent(html) {
  return String(html)
    .replace(/<!--[\s\S]*?-->/g, ' ')
    .replace(/<(script|style|svg|noscript|nav|footer|form)\b[\s\S]*?<\/\1>/gi, ' ');
}

function pageTitle(html, fallback) {
  const h1 = html.match(/<h1\b[^>]*>([\s\S]*?)<\/h1>/i);
  if (h1) return textOnly(h1[1]);
  const title = html.match(/<title\b[^>]*>([\s\S]*?)<\/title>/i);
  return title ? textOnly(title[1]).replace(/\s*\|\s*Royal Family Academy.*$/i, '') : fallback;
}

function pageUrl(site, filePath) {
  const rel = path.relative(path.join(ROOT, site.dir), filePath).replaceAll(path.sep, '/');
  if (rel === 'index.html') return site.baseUrl;
  return new URL(rel, site.baseUrl).href;
}

function makeChunks(html, title) {
  const mainMatch = html.match(/<main\b[^>]*>([\s\S]*?)<\/main>/i);
  const source = removeNonContent(mainMatch ? mainMatch[1] : html);
  const blockRe = /<(h[1-4]|p|li|summary|blockquote|td|th)\b[^>]*>([\s\S]*?)<\/\1>/gi;
  const entries = [];
  let heading = title;
  let bucket = [];
  let bucketChars = 0;

  function flush() {
    if (!bucket.length) return;
    const text = bucket.join(' ').replace(/\s+/g, ' ').trim();
    if (text.length >= 12 && !PLACEHOLDER_RE.test(text)) entries.push({ heading, text });
    bucket = [];
    bucketChars = 0;
  }

  let match;
  while ((match = blockRe.exec(source))) {
    const tag = match[1].toLowerCase();
    const text = textOnly(match[2]);
    if (!text || PLACEHOLDER_RE.test(text) || SKIP_TEXT_RE.test(text)) continue;

    if (/^h[1-4]$/.test(tag)) {
      flush();
      heading = text;
      continue;
    }

    if (tag === 'summary') continue;
    if (text.length < 3) continue;

    if (bucketChars + text.length > 1400) flush();
    bucket.push(text);
    bucketChars += text.length + 1;
  }
  flush();
  return entries;
}

const entries = [];
const seen = new Set();

for (const site of SITES) {
  const baseDir = path.join(ROOT, site.dir);
  for (const file of walk(baseDir)) {
    const html = fs.readFileSync(file, 'utf8');
    const fallback = path.basename(file, '.html').replace(/[-_]+/g, ' ');
    const title = pageTitle(html, fallback);
    const url = pageUrl(site, file);
    const rel = path.relative(ROOT, file).replaceAll(path.sep, '/');

    for (const chunk of makeChunks(html, title)) {
      const heading = chunk.heading || title;
      const text = chunk.text;
      const key = `${site.key}\n${heading}\n${text}`.toLowerCase();
      if (seen.has(key)) continue;
      seen.add(key);
      entries.push({
        site: site.key,
        page: title,
        heading,
        text,
        url,
        path: rel
      });
    }
  }
}

entries.sort((a, b) =>
  a.site.localeCompare(b.site) || a.path.localeCompare(b.path) || a.heading.localeCompare(b.heading)
);

const output = `/**\n * AUTO-GENERATED by scripts/build-rfa-search-index.mjs.\n * Do not hand-edit. It contains only visitor-facing text extracted from the current RFA HTML pages.\n */\nwindow.RFA_SITE_INDEX = ${JSON.stringify({ version: 1, entries }, null, 2)};\n`;

const outPath = path.join(ROOT, 'shared/js/rfa-site-index.js');
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, output, 'utf8');
console.log(`Wrote ${entries.length} verified website-search entries to shared/js/rfa-site-index.js`);
